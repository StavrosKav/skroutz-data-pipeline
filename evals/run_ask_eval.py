"""Run the /ask eval against the real DB + NIM.

    python evals/run_ask_eval.py [--only ID ...] [--out evals/last_run.json] [--report PATH]

Needs DB_* and NIM_API_KEY in .env. Read-only: every query runs through the
same read-only executor the bot uses. Target: >= 80% of the items, rounded up
(19/23 for the current set). --report writes a committable Markdown summary
(default evals/results/ask_eval_<date>.md); last_run.json stays gitignored.
"""

from __future__ import annotations

import argparse
import datetime as dt
import json
import math
import re
import sys
import time
from pathlib import Path

BASE = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(BASE))

from dotenv import load_dotenv  # noqa: E402

from agents.ask.agent import AskAgent  # noqa: E402
from agents.ask.runtime import LAST_MODEL, make_nim_llm, make_pg_executor  # noqa: E402
from evals.checks import check  # noqa: E402

EVAL_FILE = BASE / "evals" / "ask_eval.yaml"
TARGET_RATIO = 0.8


def target_for(n: int) -> int:
    return math.ceil(TARGET_RATIO * n)


def write_report(path: Path, results: list[dict], date: str) -> None:
    passed = sum(1 for r in results if r["ok"])
    models = sorted({r.get("model") or "?" for r in results})
    lines = [f"# /ask eval run {date}", "",
             f"Score: **{passed}/{len(results)}** (target {target_for(len(results))}/{len(results)})", "",
             f"Model(s) that answered: {', '.join(f'`{m}`' for m in models)}", "",
             "Generated by `python evals/run_ask_eval.py` against the live DB (read-only role)", "",
             "| Question | Result | Detail | Model | Latency ms |", "|---|---|---|---|---|"]
    for r in results:
        why = str(r.get("why", "")).replace("|", "/").replace("\n", " ")[:120]
        lines.append(f"| {r['id']} | {'PASS' if r['ok'] else 'FAIL'} | {why} | {r.get('model') or '?'} | {r.get('latency_ms', '')} |")
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def load_items(path: Path = EVAL_FILE) -> list[dict]:
    text = path.read_text(encoding="utf-8")
    try:
        data = json.loads(text)
    except json.JSONDecodeError:
        import yaml  # optional; only if the file is hand-edited into block YAML
        data = yaml.safe_load(text)
    return data["items"]


def _transient(error) -> bool:
    """agent.ask reports unexpected errors as a bare exception type name
    (for example HTTPStatusError or ReadTimeout). Guard rejections are sentences."""
    return bool(error) and bool(re.fullmatch(r"\w+", str(error))) and error != "SQLGuardError"


def run_item(agent, it: dict, execute, tries: int = 3, sleep=time.sleep) -> dict:
    """Run one eval item. NIM errors (429, 404, 5xx, timeouts) are retried with
    backoff (2 s, 4 s). If they still fail, the item is a FAIL with the error,
    so one bad call never stops the whole run."""
    try:
        ref_cols, ref_rows = ([], [])
        if it.get("reference_sql"):
            c, rr = execute(it["reference_sql"])
            ref_cols, ref_rows = list(c), [list(x) for x in rr]
    except Exception as exc:  # noqa: BLE001
        return {"id": it["id"], "ok": False, "why": f"reference error: {type(exc).__name__}",
                "sql": None, "answer": None, "error": type(exc).__name__, "attempts": 0,
                "latency_ms": None, "model": None, "tries": 0}
    res, err, n = None, None, 0
    for n in range(1, tries + 1):
        LAST_MODEL.clear()
        try:
            res, err = agent.ask(it["question"]), None
        except Exception as exc:  # noqa: BLE001
            res, err = None, type(exc).__name__
        if (res is not None and not _transient(res.error)) or n == tries:
            break
        sleep(2 ** n)
    if res is None:
        return {"id": it["id"], "ok": False, "why": f"NIM error after {n} tries: {err}",
                "sql": None, "answer": None, "error": err, "attempts": 0,
                "latency_ms": None, "model": LAST_MODEL.get("model"), "tries": n}
    if _transient(res.error):
        ok, why = False, f"NIM error after {n} tries: {res.error}"
    else:
        ok, why = check(it["check"], ref_cols, ref_rows, res.rows, res.answer)
    return {"id": it["id"], "ok": ok, "why": why, "sql": res.sql, "answer": res.answer,
            "error": res.error, "attempts": res.attempts, "latency_ms": res.latency_ms,
            "model": LAST_MODEL.get("model"), "tries": n}


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--only", nargs="*")
    ap.add_argument("--out", default=str(BASE / "evals" / "last_run.json"))
    ap.add_argument("--report", default=None)
    ap.add_argument("--model", default=None, help="pin one NIM model, no fallback")
    a = ap.parse_args()
    load_dotenv(BASE / ".env")

    execute = make_pg_executor()
    agent = AskAgent(make_nim_llm(model=a.model), execute, llm_attempts=1, cache_size=0)
    items = [i for i in load_items() if not a.only or i["id"] in a.only]

    results, passed = [], 0
    for it in items:
        row = run_item(agent, it, execute)
        passed += row["ok"]
        print(f"{'PASS' if row['ok'] else 'FAIL'}  {it['id']:<32} {row['why'][:100]}")
        results.append(row)

    target = target_for(len(items))
    print(f"\nAccuracy: {passed}/{len(items)}  (target {target}/{len(items)})")
    Path(a.out).write_text(json.dumps(results, ensure_ascii=False, indent=2, default=str),
                           encoding="utf-8")
    today = dt.date.today().isoformat()
    report = Path(a.report) if a.report else BASE / "evals" / "results" / f"ask_eval_{today}.md"
    write_report(report, results, today)
    print("report:", report)
    return 0 if passed >= target else 1


if __name__ == "__main__":
    raise SystemExit(main())
